/** The generated part of a project's INDEX.md: one line per library page between two markers. Pure; the file work is in library-index.ts. */
import { basename } from 'node:path';
import type { LibraryPage } from './pages.ts';
import { neutralise, safeLine } from './safe-text.ts';

export const START = '<!-- library-index:start -->';
export const END = '<!-- library-index:end -->';

/** One line per page, sorted by path: a wikilink, the kind, the read-when line, the verified-at date and a flag when the page is stale or superseded. The date, not the age, so a rerun on another day changes nothing. */
export function renderBlock(pages: LibraryPage[]): string {
  const sorted = [...pages].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const names = sorted.map((p) => basename(p.path, '.md'));
  const lines = sorted.map((p, i) => {
    const dup = names.filter((n) => n === names[i]).length > 1;
    const target = neutralise(dup ? p.path.replace(/\.md$/, '') : names[i] as string);
    const flag = p.status === 'stale' ? ' STALE' : p.status === 'superseded' ? ' SUPERSEDED' : '';
    return `- [[${target}]]: ${safeLine(p.kind, 40) || 'no kind'}, ${safeLine(p.readWhen, 140) || 'no Read when line'} (verified ${safeLine(p.verifiedAt, 40) || 'never'}${flag})`;
  });
  return [START, `Generated by library-index.ts from ${pages.length} library page${pages.length === 1 ? '' : 's'}; edit the pages, not this block.`, '', ...lines, END].join('\n');
}

export type Markers = { kind: 'none' } | { kind: 'pair'; start: number; end: number } | { kind: 'bad'; why: string };

/** Where the generated block sits in `text`: no markers at all, exactly one start line followed by exactly one end line (and the marker text nowhere else), or something else. Each marker must be alone on its line. */
export function locateBlock(text: string): Markers {
  const lines = text.split('\n').map((l) => l.trim());
  const starts = lines.flatMap((l, i) => (l === START ? [i] : []));
  const ends = lines.flatMap((l, i) => (l === END ? [i] : []));
  const mentions = text.split(START).length - 1 + (text.split(END).length - 1);
  if (!mentions) return { kind: 'none' };
  if (starts.length === 1 && ends.length === 1 && (starts[0] as number) < (ends[0] as number) && mentions === 2) return { kind: 'pair', start: starts[0] as number, end: ends[0] as number };
  return { kind: 'bad', why: `expected one "${START}" line followed by one "${END}" line and no other mention of either; found ${starts.length} start line(s), ${ends.length} end line(s), ${mentions} mention(s) in all` };
}

/** `existing` with the block between the markers replaced (`replaced`); with no markers, the block appended under a `## Pages` heading (`appended`; a hand-written page list above it is left for a person to remove). Markers that are not exactly one well-formed pair give `malformed` and the text unchanged, so no human line can be deleted or duplicated. */
export function mergeIndex(existing: string, block: string): { text: string; state: 'replaced' | 'appended' | 'malformed'; why?: string } {
  const at = locateBlock(existing);
  if (at.kind === 'bad') return { text: existing, state: 'malformed', why: at.why };
  if (at.kind === 'pair') {
    const lines = existing.split('\n');
    return { text: [...lines.slice(0, at.start), block, ...lines.slice(at.end + 1)].join('\n'), state: 'replaced' };
  }
  return { text: `${existing.replace(/\s*$/, '')}\n\n## Pages\n\n${block}\n`, state: 'appended' };
}
