// Run: node --test scripts/lib/home/handover.test.ts
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildHandover, RUN_KINDS } from './handover.ts';
import type { HandoverInput } from './handover.ts';
import type { Doc } from './docs.ts';
import type { Ticket } from '../vault/tickets.ts';
import type { Pr } from '../status-page/render.ts';

const page = { streams: ['Avonlea'], repoStreams: {}, vaultName: 'Vault', trackerUrlBase: '', ticketNotePath: '', trackerKeyPattern: '\\b[A-Z][A-Z0-9]+-\\d+\\b', tz: 'UTC' };
const ticket = (id: string, over: Partial<Ticket> = {}): Ticket => ({ id, title: `Title of ${id}`, status: 'open', type: 'task', priority: 2, labels: [], blockedBy: [], points: 0, path: `Projects/avonlea-api/Tickets/${id}.md`, project: 'avonlea-api', archived: false, body: '', ...over });
const doc = (path: string, folder: Doc['folder'], over: Partial<Doc> = {}): Doc => ({ path, folder, title: path.split('/').at(-1)?.replace(/\.md$/, '') as string, project: 'avonlea-api', kind: 'other', tickets: [], projectLevel: false, ...over });
const pr = (n: number, title: string): Pr => ({ number: n, title, url: `https://example.test/pr/${n}`, isDraft: true, baseRefName: 'develop', headRefName: `feat/${title}`, mergeable: 'MERGEABLE', mergeStateStatus: 'CLEAN', reviewDecision: null, repo: 'o/avonlea-api', short: 'avonlea-api', owner: 'o', unresolved: 0, ci: 'pass', stream: 'Avonlea' });

const CONTEXT = '---\nupdated: 2026-10-01\n---\n# Avonlea API\n\nThe sync service that feeds the orchard dashboards. It runs nightly.\n\n## Now\n\n- Cutting over to the new pipeline\n- Backfill running\n\n## Next\n\n1. Retire the old cron\n\n## Other\n\nignored\n';
const INDEX = '---\ncomponents: [loader]\n---\n# Index\n\n<!-- library-index:start -->\nGenerated by library-index.ts from 2 library pages; edit the pages, not this block.\n\n- [[orchard-sync]]: how-it-works, you change the loader (verified 2026-10-01)\n- [[run-locally]]: runbook, you set up the repo (verified 2026-09-01 STALE)\n<!-- library-index:end -->\n';

const full = (): HandoverInput => ({
  project: 'avonlea-api',
  tickets: [ticket('avonlea-api-042', { type: 'epic', status: 'in-progress', priority: 1 }), ticket('avonlea-api-043', { parent: 'avonlea-api-042', status: 'closed' }), ticket('avonlea-api-044', { parent: 'avonlea-api-042', status: 'blocked' }),
    ticket('avonlea-api-045', { parent: 'avonlea-api-042', blockedBy: ['avonlea-api-044'] }), ticket('avonlea-api-046', { parent: 'avonlea-api-042' })],
  docs: [
    doc('Projects/avonlea-api/DECISIONS.md', 'DECISIONS'), doc('Projects/avonlea-api/Plans/old.md', 'Plans', { updated: '2026-08-01' }), doc('Projects/avonlea-api/Plans/live.md', 'Plans', { status: 'active', updated: '2026-07-01' }),
    ...RUN_KINDS.map((k) => doc(`Projects/avonlea-api/Runbooks/${k}-it.md`, 'Runbooks', { tags: [k] })),
    doc('Projects/avonlea-api/Knowledge/orchard-sync.md', 'Knowledge'), doc('Projects/avonlea-api/Runbooks/run-locally.md', 'Runbooks'),
  ],
  ledger: [{ id: 'q1', ticket: 'avonlea-api-046', state: 'ask' }],
  prs: [pr(7, 'avonlea-api-046-loader'), pr(8, 'unrelated-thing')], page,
  readNote: (p) => (p.endsWith('CONTEXT.md') ? CONTEXT : p.endsWith('INDEX.md') ? INDEX : null),
});

test('a project with every section fills every section', () => {
  const h = buildHandover(full());
  assert.equal(h.overview.state, 'ok');
  if (h.overview.state === 'ok') {
    assert.equal(h.overview.summary, 'The sync service that feeds the orchard dashboards. It runs nightly.');
    assert.deepEqual([h.overview.now, h.overview.next], [['Cutting over to the new pipeline', 'Backfill running'], ['Retire the old cron']]);
    assert.equal(h.overview.ref.url, 'obsidian://open?vault=Vault&file=Projects%2Favonlea-api%2FCONTEXT');
  }
  assert.deepEqual(h.run.map((r) => [r.kind, r.state]), RUN_KINDS.map((k) => [k, 'ok']));
  assert.equal(h.blocking.clear, false);
  assert.deepEqual(h.blocking.tickets.map((t) => [t.id, t.why]), [['avonlea-api-044', 'status is blocked'], ['avonlea-api-045', 'waiting on avonlea-api-044'], ['avonlea-api-046', 'a question is waiting for an answer']]);
  assert.deepEqual(h.work.epics.map((e) => [e.id, e.closed, e.total]), [['avonlea-api-042', 1, 4]]);
  assert.equal(h.work.openTotal, 4);
  assert.deepEqual(h.work.prs.map((p) => p.label), ['avonlea-api#7']);
  assert.equal(h.library.state, 'ok');
  if (h.library.state === 'ok') {
    assert.deepEqual(h.library.groups.map((g) => [g.kind, g.lines.map((l) => [l.title, l.flag ?? null, l.ref?.url ?? null])]), [
      ['how-it-works', [['orchard-sync', null, 'obsidian://open?vault=Vault&file=Projects%2Favonlea-api%2FKnowledge%2Forchard-sync']]],
      ['runbook', [['run-locally', 'STALE', 'obsidian://open?vault=Vault&file=Projects%2Favonlea-api%2FRunbooks%2Frun-locally']]],
    ]);
  }
  assert.equal('state' in h.docs.decisions, false);
  assert.deepEqual(h.docs.plans.map((p) => p.title), ['live', 'old'], 'an active plan comes before a newer one');
});

test('a project with nothing names each missing section and how to fill it', () => {
  const h = buildHandover({ project: 'empty-proj', tickets: [], docs: [], ledger: [], prs: [], page });
  assert.equal(h.overview.state, 'missing');
  assert.match((h.overview as { fix: string }).fix, /CONTEXT\.md is missing or unreadable/);
  assert.deepEqual(h.run.map((r) => r.state), ['missing', 'missing', 'missing', 'missing']);
  assert.match((h.run[1] as { fix: string }).fix, /tagged "run"/);
  assert.equal(h.library.state, 'missing');
  assert.match((h.library as { fix: string }).fix, /library-index\.ts --repo empty-proj/);
  assert.deepEqual(h.docs.decisions, { state: 'missing', fix: 'No DECISIONS.md in Projects/empty-proj. Record each decision with its reason there.' });
  assert.equal(h.docs.shared.state, 'missing');
  assert.deepEqual([h.blocking.clear, h.work.openTotal, h.work.epics, h.work.prs], [true, 0, [], []]);
});

test('an INDEX with no page lines and a CONTEXT with no paragraph are missing, not empty', () => {
  const h = buildHandover({ ...full(), readNote: (p) => (p.endsWith('CONTEXT.md') ? '# Only a title\n\n## Now\n\n- x\n' : '# Index\n\n<!-- library-index:start -->\nGenerated.\n<!-- library-index:end -->\n') });
  assert.match((h.overview as { fix: string }).fix, /no opening paragraph/);
  assert.match((h.library as { fix: string }).fix, /lists no library pages/);
});

test('control characters and over-long lines are cleaned, and a PR with a non-http URL is not linked', () => {
  const h = buildHandover({ ...full(), prs: [{ ...pr(9, 'avonlea-api-046-x'), url: 'javascript:alert(1)' }], readNote: (p) => (p.endsWith('CONTEXT.md') ? `# T\n\nA\u0007B ${'x'.repeat(900)}\n` : null) });
  assert.ok(h.work.prs.length === 0);
  assert.ok(h.overview.state === 'ok' && !/[\u0000-\u001f]/.test(h.overview.summary) && h.overview.summary.length <= 600);
});
